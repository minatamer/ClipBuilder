// Control/API integration only: AI adapters and native media jobs are test doubles.
// A real JPEG is generated by the existing fake picture adapter; no owner media,
// provider credentials, external requests or native video encoding is involved.
const source = Buffer.from("synthetic editor source bytes"),
  auth = { Authorization: "Bearer editor-test" },
  json = { ...auth, "Content-Type": "application/json" };
type Context = {
  host: ReturnType<typeof createOwnerHost>;
  port: number;
  root: string;
  media: ReturnType<typeof vi.fn<OwnerHostOptions["media"]>>;
};
let directory: string, storageRoot: string, contexts: Context[];
const analysis = {
  mode: "synthetic-ai" as const,
  transcribe: vi.fn(fakeOwnerAnalysis.transcribe),
  select: vi.fn(fakeOwnerAnalysis.select),
};
const preparation = {
  mode: "synthetic-ai" as const,
  plan: vi.fn(fakeOwnerClipPreparation.plan),
  image: vi.fn(fakeOwnerClipPreparation.image),
};
beforeEach(async () => {
  vi.clearAllMocks();
  directory = await mkdtemp(join(tmpdir(), "clipbuilder-owner-editor-api-"));
  storageRoot = join(directory, "private-storage");
  contexts = [];
});
afterEach(async () => {
  try {
    for (const context of contexts) {
      await stop(context);
      expect(await readdir(context.root)).toEqual([]);
    }
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});
async function start(withAI = true): Promise<Context> {
  const root = join(directory, `scratch-${contexts.length}`);
  await mkdir(root);
  const media = vi.fn<OwnerHostOptions["media"]>(async (job, signal) => {
    signal.throwIfAborted();
    if (job.operation === "inspect") {
      if (!withAI) throw new Error("unexpected_source_reinspection");
      return {
        operation: "inspect",
        source: {
          fingerprint: createHash("sha256").update(source).digest("hex"),
          bytes: source.length,
          durationMs: 16000,
          width: 320,
          height: 180,
          fps: 30,
        },
      };
    }
    if (job.operation !== "clip") throw new Error("unexpected_media_operation");
    const output = Buffer.from(
      `synthetic:${job.clipId}:${job.renderRevision}:${JSON.stringify(job.overlay)}`,
    );
    await writeFile(
      join(root, job.workspaceId, `${job.clipId}.r${job.renderRevision}.mp4`),
      output,
    );
    return {
      operation: "clip",
      frames: job.overlay.frames,
      bytes: output.length,
      durationMs: Math.round((job.overlay.frames * 1000) / 30),
    };
  });
  const host = createOwnerHost({
    root,
    storageRoot,
    ui: directory,
    token: "editor-test",
    port: 0,
    media,
    ...(withAI ? { analysis, clipPreparation: preparation } : {}),
  });
  const context = { host, root, media, port: await listenOwner(host.server) };
  contexts.push(context);
  return context;
}
async function stop(context: Context) {
  if (context.host.server.listening) await context.host.close();
  expect(context.host.server.listening).toBe(false);
}
const endpoint = (id: string) => `/api/workspace/${id}`;
const post = (context: Context, path: string, value?: unknown) =>
  ownerRequest(context.port, path, {
    method: "POST",
    headers: value === undefined ? auth : json,
    ...(value === undefined ? {} : { body: JSON.stringify(value) }),
  });
async function clips(context: Context, id: string) {
  const result = await ownerRequest(context.port, `${endpoint(id)}/clips`, {
    headers: auth,
  });
  expect(result.status).toBe(200);
  return ownerClipListSchema.parse(JSON.parse(result.body.toString()));
}
async function completed(context: Context, id: string) {
  for (let attempt = 0; attempt < 200; attempt++) {
    const result = await clips(context, id);
    if (!result.active) return result;
    await new Promise((done) => setTimeout(done, 5));
  }
  throw new Error("synthetic_editor_work_did_not_drain");
}
async function prepare(context: Context) {
  const upload = await ownerRequest(context.port, "/api/source", {
    method: "POST",
    headers: { ...auth, "Content-Type": "video/mp4" },
    body: source,
  });
  expect(upload.status).toBe(200);
  const workspace = ownerWorkspaceSchema.parse(
      JSON.parse(upload.body.toString()),
    ),
    analyzed = await post(context, `${endpoint(workspace.id)}/analysis`, {
      sourceRevision: 0,
      policyRevision: 1,
      ranges: [
        { id: randomUUID(), startMs: 200, endMs: 1200 },
        { id: randomUUID(), startMs: 2000, endMs: 4000 },
      ],
      aiDuration: { minMs: 10000, maxMs: 10000 },
      manualOnly: false,
    });
  expect(analyzed.status).toBe(200);
  const result = ownerAnalysisSchema.parse(
    JSON.parse(analyzed.body.toString()),
  );
  expect(
    (
      await post(context, `${endpoint(workspace.id)}/clips`, {
        operationId: randomUUID(),
        analysisId: result.id,
        sourceRevision: 0,
        policyRevision: 1,
        momentIds: [...result.manual, result.suggestions[0]!].map(
          (moment) => moment.id,
        ),
      })
    ).status,
  ).toBe(202);
  const list = await completed(context, workspace.id);
  expect(list.clips.map((clip) => clip.state)).toEqual([
    "ready",
    "ready",
    "ready",
  ]);
  return { workspace, list };
}
const edit = (
  clip: OwnerClip,
  operations: OwnerEditRequest["operations"],
): OwnerEditRequest => ({
  operationId: randomUUID(),
  expectedRevision: clip.revision,
  baseHash: clip.baseHash!,
  operations,
});
async function output(
  context: Context,
  id: string,
  clipId: string,
  revision = 0,
) {
  const result = await ownerRequest(
    context.port,
    `${endpoint(id)}/clips/${clipId}/output/${revision}`,
    { headers: auth },
  );
  expect(result.status).toBe(200);
  return result.body;
}
function counts(context: Context, renders: number) {
  expect(analysis.transcribe).toHaveBeenCalledTimes(1);
  expect(analysis.select).toHaveBeenCalledTimes(1);
  expect(preparation.plan).toHaveBeenCalledTimes(3);
  expect(preparation.image).toHaveBeenCalledTimes(3);
  expect(context.media).toHaveBeenCalledTimes(1 + renders);
}

it("freezes the admitted picture/edit during a held render and uses the replacement only for a later explicit export", async () => {
  const context = await start(),
    { workspace, list } = await prepare(context),
    first = list.clips[0]!,
    path = `${endpoint(workspace.id)}/clips/${first.id}`,
    original = await output(context, workspace.id, first.id),
    priorVisual = first.base!.overlay.visuals[0]!,
    nativeRender = context.media.getMockImplementation()!;
  let enter!: () => void, release!: () => void;
  const entered = new Promise<void>((done) => {
      enter = done;
    }),
    held = new Promise<void>((done) => {
      release = done;
    });
  context.media.mockImplementationOnce(async (job, signal) => {
    enter();
    await held;
    signal.throwIfAborted();
    return nativeRender(job, signal);
  });
  try {
    expect(
      (
        await post(context, `${path}/render`, {
          operationId: randomUUID(),
          expectedRevision: 0,
        })
      ).status,
    ).toBe(202);
    await entered;
    const admitted = context.media.mock.calls.at(-1)![0];
    if (admitted.operation !== "clip") throw new Error("expected_clip_job");
    const frozen = structuredClone(admitted),
      personal = await preparation.image.mock.results[0]!.value,
      imported = await ownerRequest(context.port, `${path}/picture`, {
        method: "POST",
        headers: { ...auth, "Content-Type": "image/jpeg" },
        body: personal.bytes,
      });
    expect(imported.status).toBe(200);
    const importedClip = ownerClipListSchema.parse(
        JSON.parse(imported.body.toString()),
      ).clips[0]!,
      replacement = importedClip.assets.find(
        (asset) => asset.origin === "owner-supplied",
      )!;
    expect(replacement).toBeDefined();
    expect(
      (
        await post(
          context,
          `${path}/edit`,
          edit(importedClip, [
            { kind: "caption", style: OWNER_CAPTION_PRESETS.bold },
            {
              kind: "visual-upsert",
              cue: {
                id: priorVisual.id,
                assetId: replacement.id,
                startFrame: 5,
                endFrame: 25,
                box: { x: 0.2, y: 0.3, width: 0.5, height: 0.25 },
                fit: "cover",
              },
            },
          ]),
        )
      ).status,
    ).toBe(200);
    const during = await clips(context, workspace.id);
    expect(during.active).toBe(true);
    expect(during.clips[0]?.state).toBe("rendering");
    expect(during.clips[0]?.revision).toBe(1);
    expect(during.clips[0]?.outputs).toHaveLength(1);
    expect(during.clips.slice(1)).toEqual(list.clips.slice(1));
    expect(admitted).toEqual(frozen);
    expect(admitted.overlay.captionStyle).toBeUndefined();
    expect(admitted.overlay.visuals[0]).toEqual(priorVisual);
    for (const assetId of [priorVisual.assetId, replacement.id])
      expect(
        (
          await ownerRequest(
            context.port,
            `${endpoint(workspace.id)}/assets/${assetId}`,
            { headers: auth },
          )
        ).status,
      ).toBe(200);
    expect(
      (
        await ownerRequest(context.port, endpoint(workspace.id), {
          method: "DELETE",
          headers: auth,
        })
      ).status,
    ).toBe(409);
    counts(context, 4);
    release();
    const older = await completed(context, workspace.id),
      olderBytes = await output(context, workspace.id, first.id, 1);
    expect(older.clips[0]?.state).toBe("validated-revision");
    expect(older.clips[0]?.outputs.map((item) => item.editRevision)).toEqual([
      0, 0,
    ]);
    // Finishing the old job does not enqueue a new render for the later draft.
    counts(context, 4);
    expect(
      (
        await post(context, `${path}/render`, {
          operationId: randomUUID(),
          expectedRevision: 1,
        })
      ).status,
    ).toBe(202);
    const latest = await completed(context, workspace.id),
      nextJob = context.media.mock.calls.at(-1)![0];
    if (nextJob.operation !== "clip") throw new Error("expected_clip_job");
    expect(nextJob.overlay.captionStyle).toEqual(OWNER_CAPTION_PRESETS.bold);
    expect(nextJob.overlay.visuals[0]).toEqual(
      expect.objectContaining({
        assetId: replacement.id,
        digest: replacement.digest,
        origin: "owner-supplied",
        startFrame: 5,
        endFrame: 25,
        fit: "cover",
      }),
    );
    expect(latest.clips[0]?.outputs.map((item) => item.editRevision)).toEqual([
      0, 0, 1,
    ]);
    expect(latest.clips.slice(1)).toEqual(list.clips.slice(1));
    expect(await output(context, workspace.id, first.id)).toEqual(original);
    expect(await output(context, workspace.id, first.id, 1)).toEqual(
      olderBytes,
    );
    expect(await output(context, workspace.id, first.id, 2)).not.toEqual(
      olderBytes,
    );
    expect(
      await readFile(join(context.root, workspace.id, "source.mp4")),
    ).toEqual(source);
    counts(context, 5);
  } finally {
    release();
  }
});

it("imports a personal picture and edits/re-exports one of three clips with stale-write isolation and no extra AI", async () => {
  const context = await start(),
    { workspace, list } = await prepare(context),
    first = list.clips[0]!,
    path = `${endpoint(workspace.id)}/clips/${first.id}`,
    original = await output(context, workspace.id, first.id),
    personal = await preparation.image.mock.results[0]!.value;
  const imported = await ownerRequest(context.port, `${path}/picture`, {
    method: "POST",
    headers: { ...auth, "Content-Type": "image/jpeg" },
    body: personal.bytes,
  });
  expect(imported.status).toBe(200);
  const importedClip = ownerClipListSchema.parse(
      JSON.parse(imported.body.toString()),
    ).clips[0]!,
    asset = importedClip.assets.find(
      (item) => item.origin === "owner-supplied",
    )!,
    visual = first.base!.overlay.visuals[0]!,
    captionStyle = { ...OWNER_CAPTION_PRESETS.classic, align: "left" as const };
  expect(asset).toBeDefined();
  const changed = await post(
    context,
    `${path}/edit`,
    edit(importedClip, [
      { kind: "caption", style: captionStyle },
      {
        kind: "visual-upsert",
        cue: {
          id: visual.id,
          assetId: asset.id,
          startFrame: 3,
          endFrame: 27,
          box: { x: 0.1, y: 0.4, width: 0.6, height: 0.2 },
          fit: "cover",
        },
      },
    ]),
  );
  expect(changed.status).toBe(200);
  const current = ownerClipListSchema.parse(JSON.parse(changed.body.toString()))
    .clips[0]!;
  expect(current.revision).toBe(1);
  expect(current.edit?.captions).toEqual(captionStyle);
  expect(current.edit?.visuals[0]?.assetId).toBe(asset.id);
  expect(current.outputs[0]?.editRevision).toBe(0);
  counts(context, 3);
  const competing = await Promise.all(
    (["left", "right"] as const).map((align) =>
      post(
        context,
        `${path}/edit`,
        edit(current, [
          {
            kind: "caption",
            style: { ...captionStyle, align },
          },
        ]),
      ),
    ),
  );
  expect(competing.map((result) => result.status).sort()).toEqual([200, 409]);
  const latest = (await clips(context, workspace.id)).clips[0]!;
  expect(latest.revision).toBe(2);
  expect(
    (
      await post(
        context,
        `${path}/edit`,
        edit(latest, [
          {
            kind: "visual-upsert",
            cue: {
              id: visual.id,
              assetId: randomUUID(),
              startFrame: 0,
              endFrame: 20,
              box: visual.box,
              fit: "contain",
            },
          },
        ]),
      )
    ).status,
  ).toBe(400);
  expect(
    (
      await post(context, `${path}/edit`, {
        ...edit(latest, [{ kind: "reset", panel: "captions" }]),
        baseHash: "b".repeat(64),
      })
    ).status,
  ).toBe(409);
  expect((await clips(context, workspace.id)).clips[0]?.revision).toBe(2);
  counts(context, 3);
  expect(
    (
      await post(context, `${path}/render`, {
        operationId: randomUUID(),
        expectedRevision: 2,
      })
    ).status,
  ).toBe(202);
  const exported = await completed(context, workspace.id);
  expect(exported.clips[0]?.outputs.map((item) => item.editRevision)).toEqual([
    0, 2,
  ]);
  expect(exported.clips.slice(1)).toEqual(list.clips.slice(1));
  expect(await output(context, workspace.id, first.id)).toEqual(original);
  expect(await output(context, workspace.id, first.id, 1)).not.toEqual(
    original,
  );
  const rendered = context.media.mock.calls.at(-1)![0];
  if (rendered.operation !== "clip") throw new Error("expected_clip_job");
  expect(rendered.overlay.visuals[0]?.origin).toBe("owner-supplied");
  expect(rendered.overlay.visuals[0]?.digest).toBe(asset.digest);
  expect(rendered.overlay.captionStyle).toEqual(latest.edit?.captions);
  counts(context, 4);
});

it("flushes an acknowledged pending autosave before shutdown discards the in-memory clip bundles", async () => {
  const initial = await start(),
    { workspace, list } = await prepare(initial),
    previousOutputs = await Promise.all(
      list.clips.map((clip) => output(initial, workspace.id, clip.id)),
    ),
    saved = await post(initial, `${endpoint(workspace.id)}/draft`);
  expect(saved.status).toBe(200);
  const status = ownerDraftStatusSchema.parse(
    JSON.parse(saved.body.toString()),
  );
  expect(status.state).toBe("saved");
  expect(status.id).not.toBeNull();
  const first = list.clips[0]!,
    acknowledged = await post(
      initial,
      `${endpoint(workspace.id)}/clips/${first.id}/edit`,
      edit(first, [{ kind: "caption", style: OWNER_CAPTION_PRESETS.classic }]),
    );
  expect(acknowledged.status).toBe(200);
  const edited = ownerClipListSchema.parse(
    JSON.parse(acknowledged.body.toString()),
  );
  expect(edited.clips[0]?.revision).toBe(1);
  // No explicit Save or timer delay: close must flush the still-pending autosave
  // while the snapshot callback can still read every clip and admitted asset.
  await stop(initial);
  const restored = await start(false),
    opened = await post(restored, `/api/drafts/${status.id}/open`);
  expect(opened.status).toBe(200);
  const reopened = ownerWorkspaceSchema.parse(
      JSON.parse(opened.body.toString()),
    ),
    loaded = await clips(restored, reopened.id);
  expect(reopened.mode).toBe("unavailable");
  expect(loaded.clips).toHaveLength(3);
  expect(loaded.clips).toEqual(edited.clips);
  expect(loaded.clips[0]?.edit?.captions).toEqual(
    OWNER_CAPTION_PRESETS.classic,
  );
  for (const [index, clip] of loaded.clips.entries()) {
    expect(clip.assets).toHaveLength(1);
    expect(
      (
        await ownerRequest(
          restored.port,
          `${endpoint(reopened.id)}/assets/${clip.assets[0]!.id}`,
          { headers: auth },
        )
      ).status,
    ).toBe(200);
    expect(await output(restored, reopened.id, clip.id)).toEqual(
      previousOutputs[index],
    );
  }
  expect(restored.media).toHaveBeenCalledTimes(0);
  counts(initial, 3);
});

it("saves and autosaves locally, then restores/edit/exports on a new host with every AI adapter unavailable", async () => {
  const initial = await start(),
    { workspace, list } = await prepare(initial),
    first = list.clips[0]!,
    path = `${endpoint(workspace.id)}/clips/${first.id}`,
    original = await output(initial, workspace.id, first.id);
  expect(
    (
      await post(
        initial,
        `${path}/edit`,
        edit(first, [
          { kind: "caption", style: OWNER_CAPTION_PRESETS.classic },
        ]),
      )
    ).status,
  ).toBe(200);
  const saved = await post(initial, `${endpoint(workspace.id)}/draft`);
  expect(saved.status).toBe(200);
  const status = ownerDraftStatusSchema.parse(
    JSON.parse(saved.body.toString()),
  );
  expect(status.state).toBe("saved");
  expect(status.id).not.toBeNull();
  const savedStatus = await ownerRequest(
    initial.port,
    `${endpoint(workspace.id)}/draft`,
    { headers: auth },
  );
  expect(savedStatus.status).toBe(200);
  expect(
    ownerDraftStatusSchema.parse(JSON.parse(savedStatus.body.toString())),
  ).toEqual(status);
  const current = (await clips(initial, workspace.id)).clips[0]!;
  expect(
    (
      await post(
        initial,
        `${path}/edit`,
        edit(current, [{ kind: "caption", style: OWNER_CAPTION_PRESETS.bold }]),
      )
    ).status,
  ).toBe(200);
  // Clearing flushes the opted-in autosave without relying on a wall-clock delay.
  expect(
    (
      await ownerRequest(initial.port, endpoint(workspace.id), {
        method: "DELETE",
        headers: auth,
      })
    ).status,
  ).toBe(204);
  counts(initial, 3);
  await stop(initial);
  expect(await readdir(initial.root)).toEqual([]);
  const savedSources = await readdir(join(storageRoot, "Sources")),
    savedExports = await readdir(join(storageRoot, "Exports"));
  expect(savedSources).toHaveLength(1);
  expect(savedExports.length).toBeGreaterThan(0);
  const restored = await start(false),
    summaries = await ownerRequest(restored.port, "/api/drafts", {
      headers: auth,
    });
  expect(
    ownerDraftListSchema
      .parse(JSON.parse(summaries.body.toString()))
      .map((item) => item.id),
  ).toEqual([status.id]);
  const opened = await post(restored, `/api/drafts/${status.id}/open`);
  expect(opened.status).toBe(200);
  const reopened = ownerWorkspaceSchema.parse(
    JSON.parse(opened.body.toString()),
  );
  expect(reopened.id).not.toBe(workspace.id);
  expect(reopened.mode).toBe("unavailable");
  const loaded = (await clips(restored, reopened.id)).clips[0]!;
  expect(loaded.revision).toBe(2);
  expect(loaded.edit?.captions).toEqual(OWNER_CAPTION_PRESETS.bold);
  expect(
    (
      await ownerRequest(restored.port, `${endpoint(reopened.id)}/source`, {
        headers: auth,
      })
    ).body,
  ).toEqual(source);
  expect(await output(restored, reopened.id, loaded.id)).toEqual(original);
  expect(restored.media).toHaveBeenCalledTimes(0);
  const edited = await post(
    restored,
    `${endpoint(reopened.id)}/clips/${loaded.id}/edit`,
    edit(loaded, [{ kind: "caption", style: OWNER_CAPTION_PRESETS.clean }]),
  );
  expect(edited.status).toBe(200);
  expect(restored.media).toHaveBeenCalledTimes(0);
  expect(
    (
      await post(
        restored,
        `${endpoint(reopened.id)}/clips/${loaded.id}/render`,
        { operationId: randomUUID(), expectedRevision: 3 },
      )
    ).status,
  ).toBe(202);
  const final = await completed(restored, reopened.id);
  expect(final.clips[0]?.outputs.map((item) => item.editRevision)).toEqual([
    0, 3,
  ]);
  expect(restored.media).toHaveBeenCalledTimes(1);
  expect(restored.media.mock.calls[0]?.[0].operation).toBe("clip");
  counts(initial, 3);
  expect((await post(restored, `${endpoint(reopened.id)}/draft`)).status).toBe(
    200,
  );
  expect(
    (
      await ownerRequest(restored.port, `/api/drafts/${status.id}`, {
        method: "DELETE",
        headers: auth,
      })
    ).status,
  ).toBe(204);
  expect(await readdir(join(storageRoot, "Sources"))).toEqual(savedSources);
  expect(
    (await readdir(join(storageRoot, "Exports"))).length,
  ).toBeGreaterThanOrEqual(savedExports.length);
  expect(
    await readFile(join(restored.root, reopened.id, "source.mp4")),
  ).toEqual(source);
});
